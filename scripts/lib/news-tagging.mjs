/**
 * ニュース記事のカテゴリ・タグ判定
 *
 * 判定に使うのは **タイトルだけ** で、本文（summary）は見ない。
 * Google アラートの content には元ページのサイドバーやおすすめ記事欄が
 * そのまま混ざる。そのため本文まで見ると、記事と無関係な
 * 「イベント」「発売」「HUNTER×HUNTER」といった語を拾って誤判定する。
 * 実データ 3076 件では 66% が「コラボ」に倒れ、うち 55 件は本文中の
 * 「×」記号だけが根拠だった。
 *
 * fetch-news.mjs（新着）と reclassify-news.mjs（既存データの再判定）の
 * 両方から参照し、新旧の記事で基準がズレないようにしている。
 */

/** 「ちいかわ×ブランド」の形だけをコラボとみなす（無関係な作品名の「×」を拾わないため） */
const COLLAB_PAIR = /(ちいかわ|ハチワレ)\s*[×✕✖]|[×✕✖]\s*(ちいかわ|ハチワレ)/;

/**
 * カテゴリ判定ルール。上から順に評価し、最初に一致したものを採用する。
 * 具体的な語（興行収入・コミックス）を先に、一般的な語（発売・限定）を後に置く。
 * 「映画」は作品名『映画 ちいかわ』としてグッズ記事の見出しにも頻出するため、
 * 単独ではアニメと判定せず、上映・興収など映画そのものの話題を示す語を使う。
 */
